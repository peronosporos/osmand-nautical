        private fun bytes(hex: String): ByteArray {
            val out = ByteArray(hex.length / 2)
            for (i in out.indices) {
                out[i] = ((Character.digit(hex[i * 2], 16) shl 4) or
                        Character.digit(hex[i * 2 + 1], 16)).toByte()
            }
            return out
        }

        private fun authenticate(signatureFile: ByteArray, cell: ByteArray,
                trustedKeys: List<S63AuthVerifier.DsaKey> = emptyList()): S63AuthVerifier.Outcome {
            return S63AuthVerifier.authenticate(
                signatureFile, ByteArrayInputStream(cell), IHO_KEY, trustedKeys)
        }

        /** S-63 5.4.1.1 data string: blocks of four hex digits, full stop terminated. */
        private fun dataString(hex: String): String = hex.chunked(4).joinToString(" ") + "."
