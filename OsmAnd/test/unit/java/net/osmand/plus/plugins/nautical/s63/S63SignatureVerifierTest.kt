    @Test
    fun tamperedCellFailsEncSignature() {
        val cell = bytes(CELL_4E_001_HEX)
        cell[500] = (cell[500].toInt() xor 0xFF).toByte()
        assertEquals(S63AuthVerifier.Outcome.CellSignatureInvalid, authenticate(bytes(SF_4E_HEX), cell))
        val truncatedCell = cell.copyOf(cell.size - 8)
        assertEquals(S63AuthVerifier.Outcome.CellSignatureInvalid, authenticate(bytes(SF_4E_HEX), truncatedCell))
    }

