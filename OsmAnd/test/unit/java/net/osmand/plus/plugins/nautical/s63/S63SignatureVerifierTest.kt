    @Test
    fun signatureFileNameFollowsBandMapping() {
        assertEquals("GBI00001.000", S63SignatureFile.signatureFileNameFor("GB100001.000"))
        assertEquals("GBN1021A.001", S63SignatureFile.signatureFileNameFor("GB61021A.001"))
        assertEquals("GBK01620.000", S63SignatureFile.signatureFileNameFor("GB301620.000"))
        assertEquals("XXI00002.031", S63SignatureFile.signatureFileNameFor("XX100002.031"))
        // No navigational purpose digit in the third position.
        assertNull(S63SignatureFile.signatureFileNameFor("CATALOG.031"))
        assertNull(S63SignatureFile.signatureFileNameFor("GB700001.000"))
        assertNull(S63SignatureFile.signatureFileNameFor("GB000001.000"))
        assertNull(S63SignatureFile.signatureFileNameFor("GB"))
    }

    @Test
    fun ihoCertificateCarriesSchemeAdministratorKey() {
        val (key, certificate) = S63AuthVerifier.dsaKeyFromX509(bytes(IHO_CRT_4B_HEX))!!
        assertEquals(IHO_KEY, key)
        val notBefore = GregorianCalendar.getInstance().apply { time = certificate.notBefore }
        val notAfter = GregorianCalendar.getInstance().apply { time = certificate.notAfter }
        assertEquals(2003, notBefore.get(Calendar.YEAR))
        assertEquals(2013, notAfter.get(Calendar.YEAR))
        assertEquals(Calendar.AUGUST, notAfter.get(Calendar.MONTH))
        assertEquals(29, notAfter.get(Calendar.DAY_OF_MONTH))
        // The shipped certificate is expired, which is why the key is
        // embedded as public parameters without an expiry.
        assertTrue(certificate.notAfter.time < System.currentTimeMillis())
    }

