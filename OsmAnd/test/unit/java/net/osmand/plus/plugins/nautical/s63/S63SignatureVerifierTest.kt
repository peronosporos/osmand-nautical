    @Test
    fun selfSignedKeyWithInstalledCertificateTakesThirdPartyPath() {
        // S-64 test 4a with the UKHO certificate installed (SSE 26, load).
        val ukhoKey = S63AuthVerifier.dsaKeyFromX509(bytes(UKHO_CRT_4A_HEX))!!
        val signatureFile = S63SignatureFile.parse(bytes(SF_4A_SSK_HEX))!!
        // UKHO.CRT carries the public key of the 4a self-signed data server.
        assertEquals(ukhoKey.first.y, signatureFile.y)
        val outcome = S63AuthVerifier.verifyDataServerCertificate(signatureFile, IHO_KEY, listOf(ukhoKey.first))
        assertTrue(outcome is S63AuthVerifier.Outcome.ThirdPartyAuthenticated)
        assertEquals(ukhoKey.first.y, (outcome as S63AuthVerifier.Outcome.ThirdPartyAuthenticated).key.y)
    }

