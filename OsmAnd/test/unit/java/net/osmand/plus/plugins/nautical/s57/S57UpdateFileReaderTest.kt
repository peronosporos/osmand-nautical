    private fun fromHex(hex: String): ByteArray =
            ByteArray(hex.length / 2) { i -> hex.substring(i * 2, i * 2 + 2).toInt(16).toByte() }

    @Test
    fun parsesGenuineUpdateInstructions() {
        val reader = S57FileReader(ByteArrayInputStream(fromHex(UPDATE_GB100001_001_HEX)))
        val features = mutableListOf<S57Object>()
        reader.forEachFeature { features.add(it) }

        assertEquals(3, features.size)
        // Every record in this genuine update file is a Modify instruction.
        assertTrue(features.all { it.updateInstruction == 3 })
        assertTrue(features.all { it.recordVersion == 2 })

        val byId = features.associateBy { it.id }
        val area = byId.getValue(54L)
        assertEquals("PRDARE", area.acronym)
        assertEquals(S57PrimitiveType.AREA, area.primitiveType)
        val light151 = byId.getValue(151L)
        assertEquals("LIGHTS", light151.acronym)
        assertEquals(S57PrimitiveType.POINT, light151.primitiveType)
        val light152 = byId.getValue(152L)
        assertEquals("LIGHTS", light152.acronym)
        assertEquals(S57PrimitiveType.POINT, light152.primitiveType)

        // Attribute-only modifications: geometry is carried by the base cell.
        assertTrue(features.all { it.geometries.isEmpty() })
    }
